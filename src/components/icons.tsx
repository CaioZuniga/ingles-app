export function Icon({ name, size = 20, className = '', strokeWidth = 1.8 }: { name: IconName; size?: number; className?: string; strokeWidth?: number }) {
  const filled = name === 'play' || name === 'stop' || name === 'auto'
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? 'currentColor' : 'none'}
      stroke="currentColor"
      strokeWidth={filled ? 0 : strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`shrink-0 ${className}`}
      aria-hidden
    >
      <path d={PATHS[name]} />
      {name === 'auto' && <circle cx="12" cy="12" r="9.2" fill="none" stroke="currentColor" strokeWidth={1.8} />}
    </svg>
  )
}

export const SKILL_ICON: Record<Skill, IconName> = {
  vocabulary: 'book',
  grammar: 'grammar',
  listening: 'headphones',
  writing: 'pen',
  speaking: 'mic',
}

/** Ladrilho colorido com o ícone da habilidade (fundo suave + ícone na cor da habilidade). */
export function SkillTile({ skill, size = 40, done }: { skill: Skill; size?: number; done?: boolean }) {
  const color = `var(--color-${SKILL_VAR[skill]})`
  return (
    <span
      className="grid shrink-0 place-items-center rounded-xl"
      style={{ width: size, height: size, background: done ? color : `color-mix(in oklab, ${color} 16%, transparent)`, color: done ? 'var(--color-on-skill)' : color }}
    >
      <Icon name={done ? 'check' : SKILL_ICON[skill]} size={Math.round(size * 0.5)} strokeWidth={done ? 2.6 : 1.9} />
    </span>
  )
}

const SKILL_VAR: Record<Skill, string> = { vocabulary: 'voc', grammar: 'gra', listening: 'lis', writing: 'wri', speaking: 'spk' }

/** Anel de progresso (0..1). */
export function Ring({ value, size = 64, stroke = 6, color = 'var(--color-accent)', children }: { value: number; size?: number; stroke?: number; color?: string; children?: React.ReactNode }) {
  const r = (size - stroke) / 2
  const c = 2 * Math.PI * r
  const v = Math.max(0, Math.min(1, value))
  return (
    <div className="relative grid shrink-0 place-items-center" style={{ width: size, height: size }}>
      <svg width={size} height={size} className="-rotate-90">
        <circle cx={size / 2} cy={size / 2} r={r} fill="none" stroke="var(--color-line)" strokeWidth={stroke} />
        <circle cx={size / 2} cy={size / 2} r={r} fill="none" stroke={color} strokeWidth={stroke} strokeLinecap="round" strokeDasharray={c} strokeDashoffset={c * (1 - v)} style={{ transition: 'stroke-dashoffset .6s ease' }} />
      </svg>
      <div className="absolute inset-0 grid place-items-center text-center">{children}</div>
    </div>
  )
}
